def link(id,pair,question,title,text,hint,options,answer,error):
 return dict(id=id,pair=pair,question=question,title=title,text=text,hint=hint,inference=dict(options=options,answer=answer,error=error))
def field(id,label,options,answer):return dict(id=id,label=label,options=options,answer=answer)
def hotspot(id,x,y,title,body,**kw):return dict(id=id,x=x,y=y,title=title,body=body,**kw)
def scene(id,title,art,caption,hotspots,links=None):return dict(id=id,title=title,art='assets/scenes/'+art+'.jpg',caption=caption,description='由同行人陪同勘验 · 不独自进入封闭空间',hotspots=hotspots,requiresLinks=links or [])
def report(id,label,options,answer,error):return dict(id=id,label=label,options=options,answer=answer,error=error)
def ending(id,name,mark,choice,title,paragraphs,last):return dict(id=id,name=name,mark=mark,choice=choice,title=title,paragraphs=paragraphs,last=last)
